def get_all_questions():
    """Return all questions as a list for API responses"""
    return [
        {
            "question_number": num,
            "text": data["text"],
            "options": data["options"]
        }
        for num, data in sorted(PF16_QUESTIONS.items())
    ]

def get_question(question_number: int):
    """Get a specific question by number"""
    if question_number not in PF16_QUESTIONS:
        return None
    return {
        "question_number": question_number,
        "text": PF16_QUESTIONS[question_number]["text"],
        "options": PF16_QUESTIONS[question_number]["options"]
    }
